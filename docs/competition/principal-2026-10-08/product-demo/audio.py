"""Create an original procedural music bed and mix sparse Chinese narration.

Input voices are generated locally by narrate.ps1. No copyrighted music assets.
"""
from pathlib import Path
import numpy as np
import json, wave, subprocess, hashlib
SOURCE=Path(__file__).resolve().parent
ROOT=SOURCE.parents[3]
if not (ROOT/'miniprogram/app.json').exists():ROOT=SOURCE.parent
BUILD=ROOT/'artifacts/product-demo-v6'
OUT=SOURCE.parent
SR,DURATION=44100,234
voices=json.loads((BUILD/'voices.json').read_text(encoding='utf-8'))

# Original C-major pentatonic motifs, synthesized with soft harmonics.
music=np.zeros(DURATION*SR,dtype=np.float64)
for bar in range(98):
    root=[48,53,57,55][bar%4]
    for step,interval in enumerate([0,7,12,16]):
        start=int((bar*2.4+step*.6)*SR)
        if start>=len(music):continue
        length=min(int(SR*2.6),len(music)-start)
        t=np.arange(length)/SR
        hz=440*2**((root+interval-69)/12)
        attack=1-np.exp(-t*55)
        release=np.exp(-t*2.1)
        note=(np.sin(2*np.pi*hz*t)+.12*np.sin(2*np.pi*2*hz*t))*attack*release
        music[start:start+length]+=note*.036

narration=np.zeros_like(music)
voice_records=[]
for i,item in enumerate(voices):
    wav=BUILD/f'voice-{i:02}.wav'
    with wave.open(str(wav)) as f:
        source_sr=f.getframerate();channels=f.getnchannels();data=np.frombuffer(f.readframes(f.getnframes()),dtype='<i2').astype(float)/32768
    if channels>1:data=data.reshape(-1,channels).mean(axis=1)
    length=len(data)/source_sr
    next_at=voices[i+1]['at'] if i+1<len(voices) else DURATION
    if item['at']+length>next_at-.2:raise ValueError(f'Overlapping narration {i}')
    x=np.arange(round(length*SR))/SR
    resampled=np.interp(x,np.arange(len(data))/source_sr,data)
    start=round(item['at']*SR)
    rms=np.sqrt(np.mean(resampled**2))
    gain=min(2.3,.11/max(rms,1e-5))
    narration[start:start+len(resampled)]+=resampled*gain
    # Duck music under speech with smooth attack and release.
    lo=max(0,start-int(.25*SR));hi=min(len(music),start+len(resampled)+int(.3*SR))
    envelope=np.full(hi-lo,.4)
    attack=min(int(.25*SR),start-lo);release=min(int(.3*SR),hi-start-len(resampled))
    if attack:envelope[:attack]=np.linspace(1,.4,attack)
    if release:envelope[-release:]=np.linspace(.4,1,release)
    music[lo:hi]*=envelope
    voice_records.append({'at':item['at'],'duration':round(length,3),'text':item['text']})

# Soft touch sounds mark selected interactions without overpowering the voice.
for at in [x['at'] for x in json.loads((SOURCE/'showcase-model.json').read_text(encoding='utf-8'))['events'] if x['target']]:
    start=round(at*SR);t=np.arange(int(.08*SR))/SR
    sound=np.sin(2*np.pi*(780+90*np.exp(-t*60))*t)*np.exp(-t*55)*.055
    music[start:start+len(sound)]+=sound

audio=music+narration
audio*=np.minimum(1,np.arange(len(audio))/(SR*1.4))
audio*=np.minimum(1,(len(audio)-np.arange(len(audio)))/(SR*2.0))
peak=np.max(np.abs(audio))
if peak>.93:audio*=.93/peak
with wave.open(str(BUILD/'soundtrack.wav'),'wb') as f:
    f.setnchannels(1);f.setsampwidth(2);f.setframerate(SR);f.writeframes((audio*32767).astype('<i2').tobytes())

video=OUT/'校园工具-产品演示优化-v6.mp4'
subprocess.run(['ffmpeg','-y','-loglevel','error','-i',str(BUILD/'product-silent.mp4'),'-i',str(BUILD/'soundtrack.wav'),
                '-c:v','copy','-c:a','aac','-b:a','160k','-movflags','+faststart','-shortest',str(video)],check=True)
def timestamp(t):
    ms=round(t*1000);return f'{ms//3600000:02}:{ms//60000%60:02}:{ms//1000%60:02},{ms%1000:03}'
subtitles=[]
for i,v in enumerate(voice_records):subtitles.append(f'{i+1}\n{timestamp(v["at"])} --> {timestamp(v["at"]+v["duration"])}\n{v["text"]}\n')
(OUT/'校园工具-产品演示优化-v6.srt').write_text('\n'.join(subtitles),encoding='utf-8')
probe=json.loads(subprocess.check_output(['ffprobe','-v','error','-show_streams','-show_format','-of','json',str(video)]))
(BUILD/'video-validation.json').write_text(json.dumps({'nature':'HTML/CSS/JavaScript reproduced product interaction, synthetic data and fixed model responses',
    'voice':voice_records,'music':'Original procedural instrumental bed generated by this source',
    'sha256':hashlib.sha256(video.read_bytes()).hexdigest(),'probe':probe},ensure_ascii=False,indent=2),encoding='utf-8')
print(video)
